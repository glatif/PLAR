// Regenerates the database types the web app imports, from the local stack or the hosted dev project.
// Usage: npm run types (hosted dev, needs `supabase login`) · npm run types:local

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fmt } from "./lib/report.js";
import { repoRoot, supabase } from "./lib/shell.js";
import { DEV_PROJECT_REF, targetFromArgs } from "./lib/targets.js";

const OUT = resolve(repoRoot, "web/src/lib/supabase/database.types.ts");
const HEADER = "// Generated by the Supabase type generator. Do not edit by hand: run `npm run types` in harness/.\n\n";

async function main() {
  const target = targetFromArgs();
  const source = target === "local" ? ["--local"] : ["--project-id", DEV_PROJECT_REF];
  const result = await supabase(["gen", "types", "typescript", ...source, "--schema", "public"], { timeoutMs: 120_000 });
  if (!result.ok || !result.stdout.includes("export type Database")) {
    throw new Error(
      target === "dev"
        ? `Type generation failed. Run \`supabase login\` first.\n${result.stderr.trim()}`
        : `Type generation failed. Is the local stack running?\n${result.stderr.trim()}`,
    );
  }
  writeFileSync(OUT, HEADER + result.stdout);
  console.log(`\n  ${fmt.pass("✓")} Types written to web/src/lib/supabase/database.types.ts ${fmt.dim(`(from ${target})`)}\n`);
}

main().catch((error) => {
  console.error(`\n  ${fmt.fail("✗")} ${error instanceof Error ? error.message : error}\n`);
  process.exitCode = 1;
});
